export type IconName = keyof typeof ICONS;

const SVG_NS = 'http://www.w3.org/2000/svg';

/** Built node by node: the bundle must not use any HTML parsing sink. */
export function createIcon(name: IconName): SVGSVGElement {
  const svg = document.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('aria-hidden', 'true');
  svg.classList.add('verso-icon');
  const path = document.createElementNS(SVG_NS, 'path');
  path.setAttribute('d', ICONS[name]);
  svg.appendChild(path);
  return svg;
}

/** Swaps the icon inside `host` (an icon button, say) for another one. */
export function setIcon(host: Element, name: IconName): void {
  const path = host.querySelector('.verso-icon path');
  if (path && path.getAttribute('d') !== ICONS[name]) path.setAttribute('d', ICONS[name]);
}

export function createIconButton(name: IconName, label: string): HTMLButtonElement {
  const button = document.createElement('button');
  button.type = 'button';
  button.className = 'verso-icon-button';
  button.setAttribute('aria-label', label);
  button.title = label;
  button.appendChild(createIcon(name));
  return button;
}
